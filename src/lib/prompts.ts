import { RESULT_OPTIONS } from "./constants";
import type { RosterPlayer } from "./types";

const OFFICIAL_LABELS_CSV = RESULT_OPTIONS.map((x) => `"${x}"`).join(", ");

export function formatRosterLines(roster: RosterPlayer[]): string {
  const lines: string[] = [];
  for (const row of roster) {
    const name = (row.player_name || "").trim();
    if (!name) continue;
    const nums = (row.uniform_number || "").trim() || "-";
    const note = (row.note || "").trim();
    const notePart = note ? `（備考:${note}）` : "";
    lines.push(`・${name}（背番号:${nums}）${notePart}`);
  }
  if (lines.length === 0) {
    return "・（名簿未登録：手書きのまま抽出し、判読不能は「未登録」とする）";
  }
  return lines.join("\n");
}

export function buildRosterPrompt(roster: RosterPlayer[]): string {
  const rosterBlock = formatRosterLines(roster);
  return `
### チーム所属選手名簿（複数背番号や同姓の区別を定義）
スコアブックの左端に書かれた手書き文字および背番号は、以下の登録名簿と照合して特定してください：
${rosterBlock}

### 役割
あなたは学童野球の手書きスコアブック（早稲田式）の「出場選手名簿抽出」の専門AIです。
スコアブックの左端にある「打順・背番号・選手名・守備位置」の列のみを精査し、出場選手の一覧を正確に抽出してください。

### 思考プロセス（3段階ダブル照合）
1. 打順1番から9番までを上から下へ走査する。上下二段書き（上段: 先発 / 下段: 交代・代打）も漏れなく確認する。
2. 【名前の輪郭照合（第一優先）】:
   - スコアに書かれた手書き文字の字形・画数・文字数を、上記の自チーム選手名簿と突き合わせ、最も合致する登録選手名に補正する。
3. 【背番号によるアシスト（第二優先）】:
   - 同姓の選手がいる場合や、手書きの名前が潰れていて候補が複数ある場合は、左端の背番号（公式戦用または練習試合用）と照合して一意に特定する。
4. 背番号と選手名簿のどちらにも該当しない場合のみ、例外として手書きのまま抽出、または「未登録」とする。

### 立ち入り禁止区域（絶対に読み取らないこと）
- スコアシート最上部のイニング数字（1〜9）
- 右側のひし形マス目（打席結果）
- シート最下部の投球数、合計得点、審判名、メモ欄

### 制約条件
- [必須]: 上下二段書きがある場合、上段の選手と下段の選手を必ず別々のオブジェクトとして出力すること。
- [禁止]: 読み取れない文字を勝手に一般的なプロ野球選手名などで推測補完すること。判読不能な部分は「未登録」とすること。

### 出力フォーマット（JSON配列のみを出力）
[
  {
    "batting_order": 1,
    "uniform_number": "10",
    "player_name": "山田",
    "is_substitute": false
  },
  {
    "batting_order": 1,
    "uniform_number": "15",
    "player_name": "田中",
    "is_substitute": true
  }
]
`.trim();
}

export function buildDetailsPrompt(rosterJson: string): string {
  return `
### 役割
あなたは学童野球の手書きスコアブック（早稲田式）の「打撃結果・安打結線」を高精度に判定する専門AIです。
事前に確定された【選手リスト】に基づき、スコアブック画像および赤ペン強調画像から、各選手の1回〜7回の打席結果、打点、盗塁数を判定してください。

### 【選手リスト】
${rosterJson}

### 【絶対厳守】迷ったら推測せず「要確認」にする白旗ルール
- 本チームのスコアブックは文字による「HR」等のメモがなく、純粋に「赤線のみ」で安打種別を記録しています。
- 保護者による手書きのインク太さ・滲み・重なりによって判定が曖昧な場合は、必ず結果を "要確認" としてください。

### サボり・読み飛ばし防止ルール（全マス完全走査の義務付け）
- 対象となる選手全員について、必ず「第1回」から「第7回」までの全7マスを1マスも省略せずに順番にチェックしてください。
- 打席が回っていないイニングは必ず "なし" と明記してください。

### 【絶対厳守】イニング列ズレ・左詰め防止ルール（垂直グリッド基準）
1. 最上部の印刷数字（1〜7）を真下に下ろしてマスを特定せよ。
2. 空白マスは絶対にスキップせず "なし" を割り当てよ。
3. 他の打者の列位置と照合し、同じ縦列にあるマス目を同一イニングとして確定せよ。

### 【判定ルール】カラー画像による赤ペン（安打・赤文字）と黒鉛筆の識別
1. マス目内の文字・記号:
   - 「K」「KC」「空」「見」➜ 三振
   - 「四」「B」「BB」➜ 四球
   - 「死」「DB」➜ 死球
   - 「□」「サ」➜ 犠打
   - 「3A」「4-3」「8」「F」「G」、またはマス内の丸数字 ➜ 凡打
2. 安打判定（◇外枠の赤ペン結線）:
   - 辺1のみ ➜ 単打
   - 辺1+辺2 ➜ 二塁打
   - 辺1+辺2+辺3 ➜ 三塁打
   - 4辺すべて ➜ 本塁打
3. 確信が持てない場合のみ "要確認"

### 盗塁と打点
- stolen_bases: 「S」または「ㄭ」の個数
- rbi: 適時打の数字、不明なら0

### 括弧書き数字「(数字)」は進塁責任打者なので無視する。

### 出力フォーマット（指定のJSON配列のみ返却）
inningsの値には必ず次の公式ラベルのいずれかのみを使用:
${OFFICIAL_LABELS_CSV}
[
  {
    "match_date": "試合日（不明なら -）",
    "opponent": "対戦相手（不明なら -）",
    "batting_order": 1,
    "uniform_number": "10",
    "player_name": "山田",
    "is_substitute": false,
    "rbi": 1,
    "stolen_bases": 1,
    "innings": {
      "1": "単打",
      "2": "なし",
      "3": "要確認",
      "4": "なし",
      "5": "なし",
      "6": "なし",
      "7": "なし"
    },
    "highlight": "初回先頭打者安打と盗塁"
  }
]
`.trim();
}
